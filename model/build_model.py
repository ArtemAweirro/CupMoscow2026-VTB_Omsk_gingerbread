LINK_RE = re.compile(r"^='[^']+'!\$?[A-Z]+\$?\d+$")


class Registry:
    """Адреса входов (лист «Допущения») и выходов других листов."""

    def __init__(self):
        self.params = {}  # key -> (row, scenario_dependent)
        self.outs = {}    # key -> (sheet, {sc: cell})

    def ref(self, key, sc="b", local=False):
        row, scen = self.params[key]
        col = {"p": "C", "b": "D", "o": "E"}[sc] if scen else "D"
        cell = f"${col}${row}"
        return cell if local else f"'{ASM}'!{cell}"

    def out(self, key, sc="b"):
        sheet, cells = self.outs[key]
        return f"'{sheet}'!{cells[sc]}"

    def expr(self, template, sc="b", local=False):
        s = re.sub(r"\{(\w+)\}", lambda m: self.ref(m.group(1), sc, local), template)
        return re.sub(r"\[([^\]]+)\]", lambda m: self.out(m.group(1), sc), s)


R = Registry()


def style(cell, kind="calc", fmt=None):
    cell.font = {"input": F_INPUT, "bold": F_BOLD, "note": F_NOTE}.get(kind, F_BASE)
    if kind == "input":
        cell.fill = FILL_INPUT
    if kind == "calc" and isinstance(cell.value, str) and LINK_RE.match(cell.value):
        cell.font = F_LINK
    if fmt:
        cell.number_format = FMT.get(fmt, fmt)
    cell.border = BORDER


def title(ws, text, subtitle=DISCLAIMER):
    ws["A1"] = text
    ws["A1"].font = F_TITLE
    ws["A2"] = subtitle
    ws["A2"].font = F_NOTE
    ws.sheet_view.showGridLines = False


def header(ws, row, labels, start_col=1):
    for i, text in enumerate(labels):
        c = ws.cell(row=row, column=start_col + i, value=text)
        c.font = F_HDR
        c.fill = FILL_HDR
        c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        c.border = BORDER


def section(ws, row, text, ncols):
    ws.cell(row=row, column=1, value=text)
    for col in range(1, ncols + 1):
        c = ws.cell(row=row, column=col)
        c.fill = FILL_SEC
        c.font = F_BOLD


def widths(ws, spec):
    for col, w in spec.items():
        ws.column_dimensions[col].width = w


def put(ws, addr, value, kind="calc", fmt=None):
    ws[addr] = value
    style(ws[addr], kind, fmt)
    return ws[addr]


