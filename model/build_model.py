def _fill_single(ws, rows, sheet, start):
    """Одноколоночный лист: значения в C. [key] = ссылка на строку этого же листа."""
    r = start
    for item in rows:
        if item[0] == "sec":
            section(ws, r, item[1], 5)
            r += 1
            continue
        key = item[0]
        R.outs[f"{sheet}.{key}"] = (sheet, {sc: f"$C${r}" for sc in SC})
        r += 1
    r = start
    for item in rows:
        if item[0] == "sec":
            r += 1
            continue
        key, name, formula, unit, note, fmt = item
        f = re.sub(r"\[(\w+)\]", lambda m: R.outs[f"{sheet}.{m.group(1)}"][1]["b"], formula)
        put(ws, f"B{r}", name)
        put(ws, f"C{r}", "=" + R.expr(f[1:]), "calc", fmt)
        put(ws, f"D{r}", unit)
        put(ws, f"E{r}", note, "note")
        r += 1


def _fill_scen(ws, sheet, rows, start, now_col=True):
    """Лист «сейчас + 3 сценария»: D = сейчас, E/F/G = П/Б/О.

    Формула строки: dict {'now': tmpl, 'sc': tmpl} или str (одна для всех колонок).
    В шаблоне: {param}, [out] (другой лист), <key> (строка этого листа в той же колонке),
    <key@now> (колонка «сейчас» этого листа).
    """
    cols = {"now": "D", "p": "E", "b": "F", "o": "G"} if now_col else {"p": "D", "b": "E", "o": "F"}
    r = start
    rowmap = {}
    for item in rows:
        if item[0] != "sec":
            rowmap[item[0]] = r
            R.outs[f"{sheet}.{item[0]}"] = (sheet, {sc: f"${cols[sc]}${r}" for sc in SC} | (
                {"now": f"$D${r}"} if now_col else {}))
        r += 1
    r = start
    ncol = 8 if now_col else 7
    for item in rows:
        if item[0] == "sec":
            section(ws, r, item[1], ncol)
            r += 1
            continue
        key, name, unit, spec, fmt, note = item
        put(ws, f"B{r}", name)
        put(ws, f"C{r}", unit)
        for colkey, col in cols.items():
            tmpl = spec.get(colkey if colkey == "now" else "sc") if isinstance(spec, dict) else spec
            if tmpl is None:
                put(ws, f"{col}{r}", None)
                continue
            if not isinstance(tmpl, str) or not tmpl.startswith("="):
                put(ws, f"{col}{r}", tmpl, "calc", fmt)
                continue
            sc = "b" if colkey == "now" else colkey
            f = re.sub(r"<(\w+)@now>", lambda m: f"$D${rowmap[m.group(1)]}", tmpl)
            f = re.sub(r"<(\w+)>", lambda m: f"{col}{rowmap[m.group(1)]}", f)
            put(ws, f"{col}{r}", "=" + R.expr(f[1:], sc), "calc", fmt)
        put(ws, f"{get_column_letter(ncol)}{r}", note, "note")
        r += 1
    return rowmap


